#!/usr/bin/env bash
# file: tests/test_src_builder_lifecycle.sh
# Offline ownership/hook overlay tests. No firmware, Docker or network required.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
source "$ROOT/tests/test_tmp.sh"
export TMPDIR="$(routerfw_test_tmp "$ROOT")"
TMP=$(mktemp -d)
trap 'rm -rf -- "$TMP"' EXIT
awk '/^# BEGIN SOURCE OVERLAY LIFECYCLE HELPERS/ { inside=1; next } /^# END SOURCE OVERLAY LIFECYCLE HELPERS/ { inside=0; found=1; exit } inside { print } END {if (!found) exit 1}' "$ROOT/system/src_builder.sh" > "$TMP/functions.sh"
bash -n "$TMP/functions.sh"
# shellcheck source=/dev/null
source "$TMP/functions.sh"
# Normalization is a shared IB/SB library, mounted in both containers.
source "$ROOT/system/overlay_permissions.sh"
# The real container installs dos2unix. Offline fixtures emulate its text conversion.
dos2unix() {
    [[ "$1" == -q && "$2" == -- ]] || return 1
    sed -i 's/\r$//' -- "$3"
}
# Emulate only the rsync copy options used here, so host rsync is not required.
rsync() {
    [[ "$1" == -a ]] || return 1
    shift
    local exclude_hook=0 source destination
    if [[ "${1:-}" == --exclude=/hooks.sh ]]; then exclude_hook=1; shift; fi
    [[ $# == 2 ]] || return 1
    source="${1%/}"
    destination="${2%/}"
    mkdir -p -- "$destination"
    cp -a -- "$source/." "$destination/" || return 1
    if (( exclude_hook )); then rm -f -- "$destination/hooks.sh"; fi
}
pass_count=0
pass() { printf '[OK] %s\n' "$1"; pass_count=$((pass_count+1)); }
fail() { printf '[FAIL] %s\n' "$1" >&2; exit 1; }
assert_file() { [[ -f "$1" ]] || fail "Expected file: $1"; }
assert_missing() { [[ ! -e "$1" ]] || fail "Unexpected file: $1"; }
assert_eq() { [[ "$1" == "$2" ]] || fail "$3: expected <$2> got <$1>"; }
assert_failure() { local label="$1"; shift; if "$@" > "$TMP/err" 2>&1; then fail "Unexpected success: $label"; fi; }
export GIT_CONFIG_NOSYSTEM=1 GIT_CONFIG_GLOBAL="$TMP/global.gitconfig"
mkdir -p "$TMP/work" "$TMP/patches" "$TMP/overlay"
export ROUTERFW_PATCH_SOURCE="$TMP/patches" ROUTERFW_FILES_SOURCE="$TMP/overlay"
cd "$TMP/work"
git init -q
git config user.name tester
git config user.email tester@invalid
mkdir -p package/core files/etc
printf 'upstream\n' > package/core/Makefile
printf 'upstream firmware\n' > files/etc/base
printf 'untouched\n' > unrelated.txt
git add . && git commit -qm baseline
# First cycle, patched tracked file + untracked custom source and firmware overlay.
mkdir -p "$ROUTERFW_PATCH_SOURCE/package/core" "$ROUTERFW_PATCH_SOURCE/target/linux" "$ROUTERFW_FILES_SOURCE/etc"
printf 'custom\r\n' > "$ROUTERFW_PATCH_SOURCE/package/core/Makefile"
printf 'new kernel patch\n' > "$ROUTERFW_PATCH_SOURCE/target/linux/999-test.patch"
printf 'custom firmware\n' > "$ROUTERFW_FILES_SOURCE/etc/new.conf"
printf 'echo not firmware\n' > "$ROUTERFW_FILES_SOURCE/hooks.sh"
source_apply_patches > "$TMP/log" 2>&1 || { cat "$TMP/log"; fail 'first patch apply'; }
assert_eq "$(cat package/core/Makefile)" custom 'LF conversion and tracked replacement'
assert_file target/linux/999-test.patch
pass 'patch tracked replacement, new untracked file, CRLF conversion'
source_prepare_files > "$TMP/log" 2>&1 || { cat "$TMP/log"; fail 'first firmware overlay'; }
assert_file files/etc/base
assert_file files/etc/new.conf
assert_missing files/hooks.sh
printf 'generated by hook\n' > files/etc/hook.conf
source_record_files > "$TMP/log" 2>&1 || { cat "$TMP/log"; fail 'capture hook outputs'; }
pass 'files overlay precedes hooks; no deletion of upstream files and no hooks.sh payload'
# Reset tracks as real source_sync_git does. Then remove source files and hook.
git reset --hard -q HEAD
rm -- "$ROUTERFW_PATCH_SOURCE/target/linux/999-test.patch" "$ROUTERFW_FILES_SOURCE/etc/new.conf" "$ROUTERFW_FILES_SOURCE/hooks.sh"
source_apply_patches > "$TMP/log" 2>&1 || { cat "$TMP/log"; fail 'removed patch cleanup'; }
source_prepare_files > "$TMP/log" 2>&1 || { cat "$TMP/log"; fail 'removed overlay cleanup'; }
source_record_files > "$TMP/log" 2>&1 || { cat "$TMP/log"; fail 'no hook cleanup'; }
assert_missing target/linux/999-test.patch
assert_missing files/etc/new.conf
assert_missing files/etc/hook.conf
assert_file files/etc/base
assert_eq "$(cat package/core/Makefile)" custom 'current patch active after tracked reset'
pass 'deleted patch and removed hook outputs disappear on next build'
# Keep non-owned files and user data.
printf 'manual user file\n' > target/linux/manual-user.txt
printf 'manual user firmware\n' > files/etc/manual-user.conf
source_apply_patches > "$TMP/log" 2>&1 || fail 'unrelated workdir file guarded'
source_prepare_files > "$TMP/log" 2>&1 || fail 'unrelated files tree guarded'
source_record_files > "$TMP/log" 2>&1 || fail 'record unrelated files'
assert_file target/linux/manual-user.txt
assert_file files/etc/manual-user.conf
pass 'unknown files survive repeated builds and are never auto-owned'
# Patch collision with an untracked user file is not allowed.
printf 'collision source\n' > "$ROUTERFW_PATCH_SOURCE/target/linux/manual-user.txt"
assert_failure 'unmanaged patch collision' source_apply_patches
assert_eq "$(cat target/linux/manual-user.txt)" 'manual user file' 'no overwrite patch collision'
rm "$ROUTERFW_PATCH_SOURCE/target/linux/manual-user.txt"
pass 'new patch cannot overwrite an untracked user file'
# Firmware collision with untracked user file is not allowed.
printf 'collision firmware\n' > "$ROUTERFW_FILES_SOURCE/etc/manual-user.conf"
assert_failure 'unmanaged firmware collision' source_prepare_files
assert_eq "$(cat files/etc/manual-user.conf)" 'manual user firmware' 'no overwrite overlay collision'
rm "$ROUTERFW_FILES_SOURCE/etc/manual-user.conf"
pass 'new overlay cannot overwrite an untracked user file'
# Create owned output, then simulate local modification: fail closed, no deletion.
printf 'owned\n' > "$ROUTERFW_PATCH_SOURCE/target/linux/owned.patch"
source_apply_patches > "$TMP/log" 2>&1 || fail 'create own patch'
printf 'modified by someone\n' > target/linux/owned.patch
rm "$ROUTERFW_PATCH_SOURCE/target/linux/owned.patch"
assert_failure 'modified patch protected' source_apply_patches
assert_eq "$(cat target/linux/owned.patch)" 'modified by someone' 'modified patch preserved'
rm target/linux/owned.patch
source_apply_patches > "$TMP/log" 2>&1 || fail 'recover after manual conflict resolution'
pass 'user-modified managed patch fails closed and preserves changes'
# Same rule for generated firmware file.
printf 'firmware owned\n' > "$ROUTERFW_FILES_SOURCE/etc/owned.conf"
source_prepare_files > "$TMP/log" 2>&1 || fail 'create owned firmware'
source_record_files > "$TMP/log" 2>&1 || fail 'record owned firmware'
printf 'changed outside routerFW\n' > files/etc/owned.conf
rm "$ROUTERFW_FILES_SOURCE/etc/owned.conf"
assert_failure 'modified firmware protected' source_prepare_files
assert_eq "$(cat files/etc/owned.conf)" 'changed outside routerFW' 'modified firmware preserved'
rm files/etc/owned.conf
source_prepare_files > "$TMP/log" 2>&1 || fail 'recover after firmware conflict'
source_record_files > "$TMP/log" 2>&1 || fail 'record after firmware conflict'
pass 'user-modified managed firmware fails closed and preserves changes'
# Safety against untrusted /patches sources touching .git and download cache.
mkdir -p "$ROUTERFW_PATCH_SOURCE/.git" "$ROUTERFW_PATCH_SOURCE/dl"
printf 'malicious\n' > "$ROUTERFW_PATCH_SOURCE/.git/config"
assert_failure 'git metadata protection' source_apply_patches
rm "$ROUTERFW_PATCH_SOURCE/.git/config"
printf 'malicious\n' > "$ROUTERFW_PATCH_SOURCE/dl/archive"
assert_failure 'dl cache protection' source_apply_patches
rm "$ROUTERFW_PATCH_SOURCE/dl/archive"
rmdir "$ROUTERFW_PATCH_SOURCE/.git" "$ROUTERFW_PATCH_SOURCE/dl"
pass 'patch overlay cannot write .git or dl cache'
# Symlink in an overlay should never be followed or copied.
ln -s /tmp "$ROUTERFW_PATCH_SOURCE/redirect"
assert_failure 'symlink input protected' source_apply_patches
rm "$ROUTERFW_PATCH_SOURCE/redirect"
pass 'patch source symlink rejected'
# Symlink in a destination parent should never be traversed.
mkdir -p "$ROUTERFW_PATCH_SOURCE/outside" "$TMP/external"
ln -s "$TMP/external" outside
printf 'malicious\n' > "$ROUTERFW_PATCH_SOURCE/outside/payload"
assert_failure 'symlink parent protected' source_apply_patches
assert_missing "$TMP/external/payload"
rm outside "$ROUTERFW_PATCH_SOURCE/outside/payload"
pass 'destination symlink traversal rejected'
# Verify shell script structural ordering even without executing entire OpenWrt builder.
python3 -B - "$ROOT/system/src_builder.sh" <<'PY'
import sys
s=open(sys.argv[1]).read()
assert s.index('source_apply_patches || exit 1') < s.index('source_prepare_files || exit 1') < s.index('if [ -f "/overlay_files/hooks.sh" ]')
assert s.index('source_record_files || exit 1') < s.index('make defconfig')
assert 'rsync -a --delete /overlay_files/ files/' not in s
PY
pass 'source builder runs overlay before hooks and records outputs before compilation'
# NUL pairs in manifests allow file names with spaces without ambiguity.
mkdir -p "$ROUTERFW_PATCH_SOURCE/spaces"
printf 'ok\n' > "$ROUTERFW_PATCH_SOURCE/spaces/name with spaces.patch"
source_apply_patches > "$TMP/log" 2>&1 || fail 'spaces input'
assert_file 'spaces/name with spaces.patch'
rm "$ROUTERFW_PATCH_SOURCE/spaces/name with spaces.patch"
source_apply_patches > "$TMP/log" 2>&1 || fail 'spaces cleanup'
assert_missing 'spaces/name with spaces.patch'
pass 'NUL-separated ownership state safely handles spaces'
# Safe migration from a pre-manifest persistent workdir: adopt only identical files.
mkdir -p "$TMP/legacy-work" "$TMP/legacy-patches/extras" "$TMP/legacy-overlay/etc"
(
    cd "$TMP/legacy-work"
    git init -q
    git config user.name tester
    git config user.email tester@invalid
    printf 'existing legacy patch\n' > "$TMP/legacy-patches/extras/same.patch"
    mkdir -p extras files/etc
    cp "$TMP/legacy-patches/extras/same.patch" extras/same.patch
    printf 'legacy firmware\n' > "$TMP/legacy-overlay/etc/legacy.conf"
    cp "$TMP/legacy-overlay/etc/legacy.conf" files/etc/legacy.conf
    ROUTERFW_PATCH_SOURCE="$TMP/legacy-patches" ROUTERFW_FILES_SOURCE="$TMP/legacy-overlay"
    source_apply_patches > "$TMP/legacy-log" 2>&1 || { cat "$TMP/legacy-log"; exit 2; }
    grep -q 'MIGRATION.*extras/same.patch' "$TMP/legacy-log" || exit 3
    source_prepare_files > "$TMP/legacy-log" 2>&1 || exit 4
    grep -q 'MIGRATION.*files/etc/legacy.conf' "$TMP/legacy-log" || exit 5
    source_record_files > "$TMP/legacy-log" 2>&1 || exit 6
    rm "$TMP/legacy-patches/extras/same.patch" "$TMP/legacy-overlay/etc/legacy.conf"
    source_apply_patches > "$TMP/legacy-log" 2>&1 || exit 7
    source_prepare_files > "$TMP/legacy-log" 2>&1 || exit 8
    source_record_files > "$TMP/legacy-log" 2>&1 || exit 9
    [[ ! -e extras/same.patch && ! -e files/etc/legacy.conf ]] || exit 10
) || fail 'legacy identical-file adoption/migration'
pass 'first launch adopts byte-identical legacy patch and firmware files safely'
# Reject reserved metadata directories even when they are empty.
mkdir -p "$ROUTERFW_PATCH_SOURCE/.git"
assert_failure 'empty .git directory rejected' source_apply_patches
rmdir "$ROUTERFW_PATCH_SOURCE/.git"
pass 'empty reserved metadata directory is blocked before rsync'

# Hook-produced symlinks are owned as links and never dereferenced on cleanup.
source_prepare_files > "$TMP/log" 2>&1 || fail 'link baseline'
ln -s "$TMP/external" files/etc/hook-link
source_record_files > "$TMP/log" 2>&1 || fail 'record hook link'
[[ -L files/etc/hook-link ]] || fail 'hook symlink absent'
source_prepare_files > "$TMP/log" 2>&1 || fail 'clean owned hook link'
assert_missing files/etc/hook-link
assert_file files/etc/base
source_record_files > "$TMP/log" 2>&1 || fail 'post link cleanup record'
pass 'hook-generated symlink cleaned without traversing its target'

# Existing user-created symlink must be preserved (and not adopted automatically).
ln -s /var files/etc/manual-link
source_prepare_files > "$TMP/log" 2>&1 || fail 'unowned symlink baseline'
source_record_files > "$TMP/log" 2>&1 || fail 'unowned symlink record'
source_prepare_files > "$TMP/log" 2>&1 || fail 'unowned symlink survives rebuild'
[[ -L files/etc/manual-link ]] || fail 'unowned symlink removed'
source_record_files > "$TMP/log" 2>&1 || fail 'unowned symlink second record'
pass 'user-owned symlinks survive repeated builds'

# Corrupted manifest should abort and never prune files even if the digest matches.
printf 'owned protected by marker\n' > "$ROUTERFW_PATCH_SOURCE/target/linux/marker.patch"
source_apply_patches > "$TMP/log" 2>&1 || fail 'owned marker file created'
cp .routerfw_patch_owned_v1 "$TMP/valid-patch-state"
printf 'dangling-marker-bytes' >> .routerfw_patch_owned_v1
rm "$ROUTERFW_PATCH_SOURCE/target/linux/marker.patch"
assert_failure 'corrupt state rejected' source_apply_patches
assert_file target/linux/marker.patch
cp "$TMP/valid-patch-state" .routerfw_patch_owned_v1
source_apply_patches > "$TMP/log" 2>&1 || fail 'recover after corrupt marker'
assert_missing target/linux/marker.patch
pass 'truncated ownership state fails closed and protects previous files'

# Directory ownership: adding then removing the sole custom file must also
# remove its previously-created parent, even if the INPUT directory remains.
mkdir -p "$ROUTERFW_FILES_SOURCE/etc/routerfw"
printf 'routerfw-overlay-test-001\n' > "$ROUTERFW_FILES_SOURCE/etc/routerfw/overlay-probe.txt"
source_prepare_files > "$TMP/log" 2>&1 || { cat "$TMP/log"; fail 'directory owner first ON'; }
source_record_files > "$TMP/log" 2>&1 || fail 'directory owner ON record'
assert_file files/etc/routerfw/overlay-probe.txt
[[ -d files/etc/routerfw ]] || fail 'expected newly-created overlay directory'
rm "$ROUTERFW_FILES_SOURCE/etc/routerfw/overlay-probe.txt"
[[ -d "$ROUTERFW_FILES_SOURCE/etc/routerfw" ]] || fail 'test must retain empty input directory'
source_prepare_files > "$TMP/log" 2>&1 || { cat "$TMP/log"; fail 'directory owner OFF'; }
source_record_files > "$TMP/log" 2>&1 || fail 'directory owner OFF record'
assert_missing files/etc/routerfw/overlay-probe.txt
assert_missing files/etc/routerfw
assert_file files/etc/base
pass 'ON/OFF prunes owned empty directory but never the firmware root or tracked files'

# Regression: no empty input-only folder may be mirrored into SquashFS.
mkdir -p "$ROUTERFW_FILES_SOURCE/etc/unused-empty"
source_prepare_files > "$TMP/log" 2>&1 || fail 'empty input overlay source'
source_record_files > "$TMP/log" 2>&1 || fail 'empty input overlay record'
assert_missing files/etc/unused-empty
pass 'empty input directory does not reappear after OFF'

# A pre-existing directory must NOT be claimed simply because overlay put a
# managed file inside it. In particular, keep user-created empty directories.
mkdir -p files/etc/preexisting-empty "$ROUTERFW_FILES_SOURCE/etc/preexisting-empty"
printf 'inside a preexisting directory\n' > "$ROUTERFW_FILES_SOURCE/etc/preexisting-empty/owned.txt"
source_prepare_files > "$TMP/log" 2>&1 || fail 'preexisting directory overlay'
source_record_files > "$TMP/log" 2>&1 || fail 'preexisting directory record'
rm "$ROUTERFW_FILES_SOURCE/etc/preexisting-empty/owned.txt"
source_prepare_files > "$TMP/log" 2>&1 || fail 'preexisting directory OFF'
source_record_files > "$TMP/log" 2>&1 || fail 'preexisting directory OFF record'
assert_missing files/etc/preexisting-empty/owned.txt
[[ -d files/etc/preexisting-empty ]] || fail 'unowned empty directory was deleted'
pass 'pre-existing unmanaged empty directory survives overlay removal'

# Even an owned directory must not be deleted while it contains a foreign file.
mkdir -p "$ROUTERFW_FILES_SOURCE/etc/owned-with-foreign"
printf 'temporary\n' > "$ROUTERFW_FILES_SOURCE/etc/owned-with-foreign/managed.txt"
source_prepare_files > "$TMP/log" 2>&1 || fail 'owned mixed directory ON'
source_record_files > "$TMP/log" 2>&1 || fail 'owned mixed directory record'
printf 'foreign data\n' > files/etc/owned-with-foreign/user.txt
rm "$ROUTERFW_FILES_SOURCE/etc/owned-with-foreign/managed.txt"
source_prepare_files > "$TMP/log" 2>&1 || fail 'owned mixed directory OFF'
source_record_files > "$TMP/log" 2>&1 || fail 'owned mixed directory OFF record'
assert_missing files/etc/owned-with-foreign/managed.txt
assert_eq "$(cat files/etc/owned-with-foreign/user.txt)" 'foreign data' 'foreign file in managed dir preserved'
[[ -d files/etc/owned-with-foreign ]] || fail 'nonempty directory erroneously removed'
pass 'foreign contents protect otherwise owned directories from pruning'

# Crash after rsync but before source_record_files: planned files and directories
# must be removable in the next invocation without touching any other state.
mkdir -p "$ROUTERFW_FILES_SOURCE/etc/crash-owned"
printf 'planned before rsync\n' > "$ROUTERFW_FILES_SOURCE/etc/crash-owned/test.txt"
source_prepare_files > "$TMP/log" 2>&1 || fail 'planned directory creation'
assert_file files/etc/crash-owned/test.txt
rm "$ROUTERFW_FILES_SOURCE/etc/crash-owned/test.txt"
source_prepare_files > "$TMP/log" 2>&1 || fail 'planned directory cleanup after interruption'
source_record_files > "$TMP/log" 2>&1 || fail 'planned directory cleanup record'
assert_missing files/etc/crash-owned/test.txt
assert_missing files/etc/crash-owned
pass 'planned directory ownership survives interruption before post-hook record'

# Directory metadata corruption fails closed BEFORE any already-owned file is
# removed. Repairing the metadata permits a normal removal on the next pass.
mkdir -p "$ROUTERFW_FILES_SOURCE/etc/dir-state-corrupt"
printf 'must survive corrupt manifest\n' > "$ROUTERFW_FILES_SOURCE/etc/dir-state-corrupt/owned.txt"
source_prepare_files > "$TMP/log" 2>&1 || fail 'corrupt dir-state fixture creation'
source_record_files > "$TMP/log" 2>&1 || fail 'corrupt dir-state fixture record'
cp "$LIFECYCLE_FILES_DIRS_STATE" "$TMP/valid-dir-state"
printf 'malformed-footer' >> "$LIFECYCLE_FILES_DIRS_STATE"
rm "$ROUTERFW_FILES_SOURCE/etc/dir-state-corrupt/owned.txt"
assert_failure 'corrupt dir ownership state rejected' source_prepare_files
assert_file files/etc/dir-state-corrupt/owned.txt
cp "$TMP/valid-dir-state" "$LIFECYCLE_FILES_DIRS_STATE"
source_prepare_files > "$TMP/log" 2>&1 || fail 'corrupt dir-state recovery'
source_record_files > "$TMP/log" 2>&1 || fail 'corrupt dir-state recovery record'
assert_missing files/etc/dir-state-corrupt
pass 'truncated directory ownership state fails closed before file deletion'

# A symlink substituted for a managed directory must never redirect cleanup.
mkdir -p "$ROUTERFW_FILES_SOURCE/etc/link-attack"
printf 'kept in original dir\n' > "$ROUTERFW_FILES_SOURCE/etc/link-attack/owned.txt"
source_prepare_files > "$TMP/log" 2>&1 || fail 'symlink directory fixture ON'
source_record_files > "$TMP/log" 2>&1 || fail 'symlink directory fixture record'
mv files/etc/link-attack files/etc/link-attack-saved
ln -s "$TMP/external" files/etc/link-attack
printf 'external safe\n' > "$TMP/external/not-ours"
rm "$ROUTERFW_FILES_SOURCE/etc/link-attack/owned.txt"
assert_failure 'symlinked managed directory rejected' source_prepare_files
assert_eq "$(cat "$TMP/external/not-ours")" 'external safe' 'external contents untouched'
assert_file files/etc/link-attack-saved/owned.txt
rm files/etc/link-attack
mv files/etc/link-attack-saved files/etc/link-attack
source_prepare_files > "$TMP/log" 2>&1 || fail 'symlink directory recovery'
source_record_files > "$TMP/log" 2>&1 || fail 'symlink directory recovery record'
assert_missing files/etc/link-attack
pass 'symlink substitution blocks directory cleanup without traversing external tree'

# Multi-level newly created parent directories are pruned deepest-first.
mkdir -p "$ROUTERFW_FILES_SOURCE/etc/nested-owned/child/grandchild"
printf 'deep marker\n' > "$ROUTERFW_FILES_SOURCE/etc/nested-owned/child/grandchild/test.txt"
source_prepare_files > "$TMP/log" 2>&1 || fail 'nested directory ON'
source_record_files > "$TMP/log" 2>&1 || fail 'nested directory record'
assert_file files/etc/nested-owned/child/grandchild/test.txt
rm "$ROUTERFW_FILES_SOURCE/etc/nested-owned/child/grandchild/test.txt"
source_prepare_files > "$TMP/log" 2>&1 || fail 'nested directory OFF'
source_record_files > "$TMP/log" 2>&1 || fail 'nested directory OFF record'
assert_missing files/etc/nested-owned
[[ -d files/etc ]] || fail 'tracked files/etc root should remain'
pass 'all owned nested directories removed bottom-up after OFF'

# Hook-generated directories (not just hook files) must be captured and cleaned.
source_prepare_files > "$TMP/log" 2>&1 || fail 'hook-generated directory preparation'
mkdir -p files/etc/hook-made/subdir
printf 'hook-generated\n' > files/etc/hook-made/subdir/hook-owned.txt
source_record_files > "$TMP/log" 2>&1 || fail 'hook-generated directory record'
source_prepare_files > "$TMP/log" 2>&1 || fail 'hook-generated directory cleanup'
source_record_files > "$TMP/log" 2>&1 || fail 'hook-generated directory cleanup record'
assert_missing files/etc/hook-made
pass 'hook-generated directories are tracked and pruned with owned files'

# No safe evidence remains for legacy empty directories created by old versions.
# They must survive until the operator explicitly removes them via rmdir.
mkdir -p files/etc/legacy-orphan-empty
source_prepare_files > "$TMP/log" 2>&1 || fail 'legacy empty dir check'
source_record_files > "$TMP/log" 2>&1 || fail 'legacy empty dir check record'
[[ -d files/etc/legacy-orphan-empty ]] || fail 'legacy unknown empty directory was deleted'
pass 'unknown legacy orphan is never silently claimed or removed'

# Shared permissions policy must be applied BEFORE persistent files/ is changed.
mkdir -p "$ROUTERFW_FILES_SOURCE/etc/routerfw" "$ROUTERFW_FILES_SOURCE/etc/uci-defaults" \
         "$ROUTERFW_FILES_SOURCE/etc/dropbear"
printf 'marker-v1\n' > "$ROUTERFW_FILES_SOURCE/etc/routerfw/probe.txt"
printf '#!/bin/sh\necho yes\n' > "$ROUTERFW_FILES_SOURCE/etc/uci-defaults/99-permissions.sh"
printf 'ssh-ed25519 AAAA...\n' > "$ROUTERFW_FILES_SOURCE/etc/dropbear/authorized_keys"
chmod 777 "$ROUTERFW_FILES_SOURCE/etc/routerfw/probe.txt" \
          "$ROUTERFW_FILES_SOURCE/etc/uci-defaults/99-permissions.sh" \
          "$ROUTERFW_FILES_SOURCE/etc/dropbear/authorized_keys"
source_prepare_files > "$TMP/log" 2>&1 || { cat "$TMP/log"; fail 'permission staging first'; }
source_record_files > "$TMP/log" 2>&1 || fail 'permission staging record'
[[ $(stat -c %a files/etc/routerfw/probe.txt) == 644 ]] || fail 'data mode must normalize to 0644'
[[ $(stat -c %a files/etc/uci-defaults/99-permissions.sh) == 644 ]] || fail 'uci-defaults mode must normalize to 0644'
[[ $(stat -c %a files/etc/dropbear/authorized_keys) == 600 ]] || fail 'SSH key mode must normalize to 0600'
[[ $(stat -c %a files/etc/dropbear) == 700 ]] || fail 'SSH dir mode must normalize to 0700'
[[ $(stat -c %a "$ROUTERFW_FILES_SOURCE/etc/routerfw/probe.txt") == 777 ]] || fail 'host source permissions changed'
pass 'SB applies shared modes to staged files without touching host overlay'
# Changing only explicit permission metadata must be observable even if data bytes stay identical.
printf '0600 /etc/routerfw/probe.txt\n' > "$ROUTERFW_FILES_SOURCE/.routerfw-permissions"
source_prepare_files > "$TMP/log" 2>&1 || { cat "$TMP/log"; fail 'permission-only UPDATE'; }
source_record_files > "$TMP/log" 2>&1 || fail 'permission-only record'
[[ $(stat -c %a files/etc/routerfw/probe.txt) == 600 ]] || fail 'explicit mode-only update missing'
assert_missing files/.routerfw-permissions
pass 'permission-only UPDATE works and metadata is not shipped'
# Bad policy must fail before deletion of managed files.
printf '0777 /etc/routerfw/probe.txt\n' > "$ROUTERFW_FILES_SOURCE/.routerfw-permissions"
assert_failure 'invalid mode blocked before ownership cleanup' source_prepare_files
assert_file files/etc/routerfw/probe.txt
[[ $(stat -c %a files/etc/routerfw/probe.txt) == 600 ]] || fail 'invalid metadata touched persistent workdir'
rm "$ROUTERFW_FILES_SOURCE/.routerfw-permissions"
rm "$ROUTERFW_FILES_SOURCE/etc/routerfw/probe.txt" \
   "$ROUTERFW_FILES_SOURCE/etc/uci-defaults/99-permissions.sh" \
